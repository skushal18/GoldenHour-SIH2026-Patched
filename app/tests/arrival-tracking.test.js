const assert = require('assert');
const fs = require('fs');
const path = require('path');
const readModule = p => import('data:text/javascript;base64,'+fs.readFileSync(path.join(__dirname,p)).toString('base64'));
(async()=>{
 const {recordArrival}=await readModule('../src/modules/arrival.js');
 const opts={apiRoot:'https://test.invalid/api/v1',caseCode:'GH-TEST',timeoutMs:5};
 for(const status of [404,409,500]) await assert.rejects(recordArrival({...opts,fetch:async()=>({ok:false,json:async()=>({success:false})})}));
 await assert.rejects(recordArrival({...opts,socket:{connected:true,emit:(e,p,ack)=>ack({success:false})}}));
 const good=async()=>({ok:true,json:async()=>({success:true,status:'ARRIVED'})});
 assert.equal((await recordArrival({...opts,socket:{connected:true,emit:()=>{}},fetch:good})).status,'ARRIVED');
 assert.equal((await recordArrival({...opts,socket:{connected:true,emit:(e,p,ack)=>ack({success:true})}})).success,true);
 const {watchPosition}=await readModule('../src/modules/position-watch.js');
 let resolveWatch, cleared=[], updates=0;
 const plugin={requestPermissions:async()=>({location:'granted'}),watchPosition:()=>new Promise(r=>resolveWatch=r),clearWatch:async({id})=>cleared.push(id)};
 const stop=watchPosition({native:true,plugin,onPosition:()=>updates++,onError:e=>{throw e;}});
 await new Promise(r=>setTimeout(r,0));stop();resolveWatch('native-123');await new Promise(r=>setTimeout(r,0));
 assert.deepEqual(cleared,['native-123']);
 let callback;const stopBrowser=watchPosition({native:false,geolocation:{watchPosition:f=>{callback=f;return 42;},clearWatch:id=>cleared.push(id)},onPosition:()=>updates++,onError:e=>{throw e;}});
 callback({});stopBrowser();callback({});assert.equal(updates,1);assert.equal(cleared[1],42);
 /* The crew token rides on both the socket event and the HTTP fallback. */
 let sent=null, hdr=null;
 await recordArrival({...opts,crewToken:'tok-123',socket:{connected:true,emit:(e,p,ack)=>{sent=p;ack({success:true});}}});
 assert.equal(sent.crew_token,'tok-123');
 await recordArrival({...opts,crewToken:'tok-123',fetch:async(u,o)=>{hdr=o.headers;return {ok:true,json:async()=>({success:true,status:'ARRIVED'})};}});
 assert.equal(hdr['X-Crew-Token'],'tok-123');
 /* Position sharing: rough fixes are sent (marked), the socket is tried first, HTTP is the fallback. */
 const {fixFromPosition,sharePosition,describeShare}=await readModule('../src/modules/position-share.js');
 const now=Date.now(), pos=(acc,age=1000)=>({coords:{latitude:12.92,longitude:77.61,accuracy:acc,speed:10},timestamp:now-age});
 assert.equal(fixFromPosition(pos(12),now).fix.approximate,false);
 assert.equal(fixFromPosition(pos(650),now).fix.approximate,true,'a ±650 m fix is sent, marked approximate');
 assert.equal(fixFromPosition(pos(2500),now).reason,'TOO_ROUGH');
 assert.equal(fixFromPosition(pos(12,60000),now).reason,'OLD_FIX');
 assert.equal(fixFromPosition({coords:{latitude:0,longitude:0,accuracy:5},timestamp:now},now).reason,'NO_COORDS');
 assert.equal(fixFromPosition(pos(12),now).fix.speed_kmh,36);
 const fix=fixFromPosition(pos(650),now).fix;
 let viaSock=null; const sock={connected:true,emit:(e,p,ack)=>{viaSock=p;ack({success:true});}};
 let r=await sharePosition({socket:sock,caseCode:'GH-1',crewToken:'tok',fix});
 assert.equal(r.via,'socket');assert.equal(viaSock.crew_token,'tok');assert.equal(viaSock.accuracy_m,650);
 let http=null; const fetcher=async(u,o)=>{http={u,o};return {ok:true,json:async()=>({success:true})};};
 r=await sharePosition({socket:{connected:false},fetch:fetcher,apiRoot:'https://x/api/v1',caseCode:'GH-1',crewToken:'tok',fix});
 assert.equal(r.via,'http');assert.equal(http.u,'https://x/api/v1/requests/GH-1/position');assert.equal(http.o.headers['X-Crew-Token'],'tok');
 r=await sharePosition({socket:{connected:true,emit:()=>{}},fetch:fetcher,apiRoot:'https://x/api/v1',caseCode:'GH-1',crewToken:'tok',fix,timeoutMs:5});
 assert.equal(r.via,'http','a lost acknowledgement falls back to HTTP');
 r=await sharePosition({socket:{connected:true,emit:(e,p,ack)=>ack({success:false,reason:'NOT_TRACKING'})},fetch:()=>{throw new Error('must not retry');},apiRoot:'x',caseCode:'GH-1',crewToken:'tok',fix});
 assert.equal(r.reason,'NOT_TRACKING','a refusal is final, not retried over HTTP');
 r=await sharePosition({socket:null,fetch:async()=>{throw new TypeError('offline');},apiRoot:'x',caseCode:'GH-1',crewToken:'tok',fix});
 assert.equal(r.reason,'OFFLINE');
 assert.ok(describeShare({success:true,via:'http',approximate:true}).includes('Approximate'));
 assert.ok(describeShare({ok:false,reason:'TOO_ROUGH',accuracy_m:2500}).includes('2.5 km'));
 console.log('PASS: arrival failure/timeout handling, crew token on socket and HTTP, native and browser watch cancellation, position sharing (rough fixes, socket then HTTP fallback)');
})().catch(e=>{console.error(e);process.exitCode=1;});
